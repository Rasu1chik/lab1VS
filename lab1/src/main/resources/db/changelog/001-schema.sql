CREATE TABLE managers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE real_clubs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    short_name VARCHAR(3) NOT NULL UNIQUE,
    country VARCHAR(50) NOT NULL
);
CREATE TABLE players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL REFERENCES real_clubs(id),
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    position VARCHAR(3) NOT NULL CHECK (position IN ('GK','DEF','MID','FWD')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('AVAILABLE','INJURED','SUSPENDED')),
    price NUMERIC(4,1) NOT NULL CHECK (price BETWEEN 4.0 AND 15.0),
    total_points INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_players_club ON players(club_id);
CREATE INDEX idx_players_position ON players(position);
CREATE TABLE fantasy_teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manager_id BIGINT NOT NULL REFERENCES managers(id),
    name VARCHAR(50) NOT NULL,
    budget NUMERIC(5,1) NOT NULL CHECK (budget >= 0),
    total_points INTEGER NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_teams_points ON fantasy_teams(total_points DESC);
CREATE TABLE squad_players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fantasy_team_id BIGINT NOT NULL REFERENCES fantasy_teams(id) ON DELETE CASCADE,
    player_id BIGINT NOT NULL REFERENCES players(id),
    purchase_price NUMERIC(4,1) NOT NULL,
    is_captain BOOLEAN NOT NULL DEFAULT FALSE,
    is_starter BOOLEAN NOT NULL DEFAULT FALSE,
    added_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(fantasy_team_id, player_id)
);
CREATE TABLE gameweeks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number INTEGER NOT NULL UNIQUE CHECK (number > 0),
    deadline TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('UPCOMING','ACTIVE','FINISHED'))
);
CREATE TABLE player_performances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT NOT NULL REFERENCES players(id),
    gameweek_id BIGINT NOT NULL REFERENCES gameweeks(id) ON DELETE CASCADE,
    minutes_played INTEGER NOT NULL CHECK (minutes_played BETWEEN 0 AND 120),
    goals INTEGER NOT NULL CHECK (goals >= 0),
    assists INTEGER NOT NULL CHECK (assists >= 0),
    clean_sheet BOOLEAN NOT NULL,
    yellow_cards INTEGER NOT NULL CHECK (yellow_cards >= 0),
    red_cards INTEGER NOT NULL CHECK (red_cards >= 0),
    points INTEGER NOT NULL DEFAULT 0,
    UNIQUE(player_id, gameweek_id)
);
CREATE TABLE leagues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES managers(id),
    name VARCHAR(100) NOT NULL,
    type VARCHAR(10) NOT NULL CHECK (type IN ('PUBLIC','PRIVATE')),
    join_code VARCHAR(8) UNIQUE
);
CREATE TABLE league_teams (
    league_id BIGINT NOT NULL REFERENCES leagues(id) ON DELETE CASCADE,
    fantasy_team_id BIGINT NOT NULL REFERENCES fantasy_teams(id) ON DELETE CASCADE,
    PRIMARY KEY(league_id, fantasy_team_id)
);
CREATE TABLE transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fantasy_team_id BIGINT NOT NULL REFERENCES fantasy_teams(id) ON DELETE CASCADE,
    gameweek_id BIGINT NOT NULL REFERENCES gameweeks(id),
    player_in_id BIGINT NOT NULL REFERENCES players(id),
    player_out_id BIGINT NOT NULL REFERENCES players(id),
    price_in NUMERIC(4,1) NOT NULL,
    price_out NUMERIC(4,1) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (player_in_id <> player_out_id)
);
